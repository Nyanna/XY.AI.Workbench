use crate::emit::layout::Layout;
use crate::ir::{ObjectKind, Project};
use crate::emit::imports::gate_attribute;
pub const GENERATED_MARK: &str = "# generated by rustir";
pub struct Declared {
    pub name: String,
    pub module: String,
    pub kind: ObjectKind,
    pub public: bool,
    pub gate: Option<String>,
}
pub fn package_name(project: &Project) -> String {
    let raw = project
        .manifest
        .package
        .clone()
        .or_else(|| {
            project.root.file_name().map(|name| name.to_string_lossy().into_owned())
        })
        .unwrap_or_default();
    let mut name: String = raw
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '_' })
        .collect();
    if name.is_empty() {
        name = "generated".to_string();
    } else if name.starts_with(|c: char| c.is_ascii_digit()) {
        name.insert_str(0, "p_");
    }
    name
}
fn lives_in_type_namespace(kind: ObjectKind) -> bool {
    matches!(
        kind, ObjectKind::Struct | ObjectKind::Enum | ObjectKind::Union |
        ObjectKind::Trait | ObjectKind::TypeAlias
    )
}
fn is_reexported(item: &Declared, layout: &Layout) -> bool {
    item.public && item.kind != ObjectKind::Macro && item.name != "main"
        && !(lives_in_type_namespace(item.kind) && layout.is_module_name(&item.name))
}
pub fn lib_source(declared: &[Declared], layout: &Layout) -> String {
    let mut text = String::from("#![allow(unused_imports)]\n\n");
    for item in declared.iter().filter(|d| d.kind == ObjectKind::Macro) {
        let gate = gate_attribute(item.gate.as_deref());
        text.push_str(&format!("{gate}#[macro_use]\nmod {};\n", item.module));
    }
    for item in declared.iter().filter(|d| d.kind != ObjectKind::Macro) {
        let gate = gate_attribute(item.gate.as_deref());
        let prefix = if item.public { "pub " } else { "" };
        text.push_str(&format!("{gate}{prefix}mod {};\n", item.module));
    }
    let reexports: Vec<String> = declared
        .iter()
        .filter(|item| is_reexported(item, layout))
        .map(|item| {
            let gate = gate_attribute(item.gate.as_deref());
            format!("{gate}pub use {}::{};\n", item.module, item.name)
        })
        .collect();
    if !reexports.is_empty() {
        text.push('\n');
        text.extend(reexports);
    }
    text
}
pub fn main_source(package: &str, module: &str) -> String {
    format!("use {package}::{module}::main;\n")
}
pub fn cargo_source(project: &Project, package: &str, binary: bool) -> String {
    let edition = project.manifest.edition.as_deref().unwrap_or("2021");
    let mut text = format!(
        "{GENERATED_MARK}\n[package]\nname = \"{package}\"\nversion = \"0.1.0\"\nedition = \"{edition}\"\n\n[lib]\npath = \"src/lib.rs\"\n"
    );
    if binary {
        text.push_str(
            &format!("\n[[bin]]\nname = \"{package}\"\npath = \"src/main.rs\"\n"),
        );
    }
    if !project.manifest.dependencies.trim().is_empty() {
        text.push('\n');
        text.push_str(&project.manifest.dependencies);
    }
    text
}
